-- O que foi reservado para cada pedido. Sem isto, o estoque nao sabe o que
-- devolver quando o pagamento for recusado.
-- E HISTORICO: a linha nunca e apagada nem alterada. A devolucao, quando
-- acontecer, e registrada como um fato novo, em outra tabela.
-- Uma linha por item debitado: o que se devolve e a soma por SKU, ou seja,
-- exatamente o que foi debitado.
CREATE TABLE IF NOT EXISTS reserva (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id    VARCHAR(64) NOT NULL,
  sku          VARCHAR(32) NOT NULL,
  quantidade   INT         NOT NULL,
  evento_id    VARCHAR(64) NOT NULL,     -- ce_id do PedidoConfirmado que causou a reserva
  reservado_em TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS reserva_por_pedido ON reserva (pedido_id);
